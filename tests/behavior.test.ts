import { test } from "node:test";
import assert from "node:assert/strict";
import { Behavior } from "../src/behavior";
test("attention first15 then5 minutes without resetting at end of meow", () => {
  const b = new Behavior(0);
  assert.equal(b.tick(899999), null);
  assert.equal(b.tick(900000), "meow");
  b.tick(901600);
  assert.equal(b.mode, "idle");
  assert.equal(b.tick(1199999), null);
  assert.equal(b.tick(1200000), "meow");
  b.tick(1201600);
  b.interact(1300000);
  assert.equal(b.tick(1600000), null);
  assert.equal(b.tick(2200000), "meow");
});
test("sleep prevents hover and reminders, wakes after20 then resets attention", () => {
  const b = new Behavior(0);
  b.begin("sleeping", 100);
  b.hover(1000, true);
  b.hover(5000, true);
  assert.equal(b.mode, "sleeping");
  assert.equal(b.tick(1000000), null);
  b.tick(1200100);
  assert.equal(b.mode, "waking");
  b.tick(1201500);
  assert.equal(b.mode, "idle");
  assert.equal(b.nextReminder, 2101500);
});
test("drag requires hold and distance, click never emitted after drag", () => {
  const b = new Behavior();
  b.pointerDown(0, 10, 10);
  assert.equal(b.pointerMove(299, 30, 30), false);
  assert.equal(b.pointerMove(300, 11, 11), false);
  assert.equal(b.pointerMove(301, 30, 30), true);
  assert.equal(b.mode, "dragging");
  assert.equal(b.pointerUp(500), false);
  assert.equal(b.mode, "idle");
  b.pointerDown(700, 10, 10);
  assert.equal(b.pointerUp(750), true);
});
test("hover activates once and ends after8 seconds; leave rearms", () => {
  const b = new Behavior();
  b.hover(0, true);
  b.hover(1999, true);
  assert.equal(b.mode, "idle");
  b.hover(2000, true);
  assert.equal(b.mode, "chase");
  b.tick(10000);
  assert.equal(b.mode, "idle");
  b.hover(11000, true);
  b.hover(15000, true);
  assert.equal(b.mode, "idle");
  b.hover(16000, false);
  b.hover(17000, true);
  b.hover(19000, true);
  assert.equal(b.mode, "chase");
});
test("active play and dragging reset attention; suspend prevents catchup", () => {
  const b = new Behavior();
  b.begin("wand", 0);
  assert.equal(b.tick(3600000), null);
  b.stop(3600100);
  assert.equal(b.nextReminder, 4500100);
  b.suspend();
  assert.equal(b.tick(9000000), null);
  b.resume(9000000);
  assert.equal(b.mode, "idle");
  assert.equal(b.nextReminder, 9900000);
});
test("sleep can be moved without waking and retains sleep deadline", () => {
  const b = new Behavior();
  b.begin("sleeping", 0);
  b.pointerDown(100, 0, 0);
  b.pointerMove(500, 20, 0);
  b.pointerUp(700);
  assert.equal(b.mode, "sleeping");
  assert.equal(b.until, 1200000);
});
test("feeding has finite animation and no hunger state", () => {
  const b = new Behavior();
  b.begin("feeding", 0);
  b.tick(4999);
  assert.equal(b.mode, "feeding");
  b.tick(5000);
  assert.equal(b.mode, "idle");
  assert.equal(b.nextReminder, 905000);
});
test("moving sprite hit boundary during chase does not rearm automatic chase", () => {
  const b = new Behavior();
  b.hover(0, true);
  b.hover(2000, true);
  b.hover(4000, false);
  b.hover(5000, true);
  b.tick(10000);
  b.hover(10001, true);
  b.hover(15000, true);
  assert.equal(b.mode, "idle");
});
